-- ----------------------------------------------------------------------------
-- Table: dealerships
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dealerships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    operating_open_time TIME NOT NULL DEFAULT '08:00:00',
    operating_close_time TIME NOT NULL DEFAULT '18:00:00',
    time_zone VARCHAR(50) NOT NULL DEFAULT 'UTC',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_dealerships_code UNIQUE (code)
);

CREATE INDEX IF NOT EXISTS idx_dealerships_active ON dealerships (is_active);

-- ----------------------------------------------------------------------------
-- Table: service_types
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS service_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    standard_duration_minutes INT NOT NULL,
    required_skill_code VARCHAR(50) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_service_types_code UNIQUE (code),
    CONSTRAINT chk_service_types_duration CHECK (standard_duration_minutes > 0)
);

CREATE INDEX IF NOT EXISTS idx_service_types_active ON service_types (is_active);
CREATE INDEX IF NOT EXISTS idx_service_types_skill ON service_types (required_skill_code);

-- ----------------------------------------------------------------------------
-- Table: service_bays
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS service_bays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealership_id BIGINT NOT NULL,
    bay_number INT NOT NULL,
    name VARCHAR(100) NOT NULL,
    is_operational BOOLEAN NOT NULL DEFAULT TRUE,
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_service_bays_dealership FOREIGN KEY (dealership_id) REFERENCES dealerships (id) ON DELETE RESTRICT,
    CONSTRAINT uk_service_bays_dealer_number UNIQUE (dealership_id, bay_number)
);

CREATE INDEX IF NOT EXISTS idx_service_bays_dealer ON service_bays (dealership_id);
CREATE INDEX IF NOT EXISTS idx_service_bays_operational ON service_bays (dealership_id, is_operational);

-- ----------------------------------------------------------------------------
-- Table: technicians
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS technicians (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealership_id BIGINT NOT NULL,
    employee_code VARCHAR(30) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_technicians_dealership FOREIGN KEY (dealership_id) REFERENCES dealerships (id) ON DELETE RESTRICT,
    CONSTRAINT uk_technicians_code UNIQUE (employee_code)
);

CREATE INDEX IF NOT EXISTS idx_technicians_dealer ON technicians (dealership_id);
CREATE INDEX IF NOT EXISTS idx_technicians_active ON technicians (dealership_id, is_active);

-- ----------------------------------------------------------------------------
-- Table: technician_skills
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS technician_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL,
    skill_code VARCHAR(50) NOT NULL,
    certified_date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tech_skills_technician FOREIGN KEY (technician_id) REFERENCES technicians (id) ON DELETE CASCADE,
    CONSTRAINT uk_tech_skills_tech_skill UNIQUE (technician_id, skill_code)
);

CREATE INDEX IF NOT EXISTS idx_tech_skills_technician ON technician_skills (technician_id);
CREATE INDEX IF NOT EXISTS idx_tech_skills_code ON technician_skills (skill_code);

-- ----------------------------------------------------------------------------
-- Table: appointments (High-volume transactional table with UUID PK)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS appointments (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    reference_number VARCHAR(32) NOT NULL,
    customer_id UUID NOT NULL,
    vehicle_vin VARCHAR(17) NOT NULL,
    dealership_id BIGINT NOT NULL,
    service_type_id BIGINT NOT NULL,
    service_bay_id BIGINT NOT NULL,
    technician_id BIGINT NOT NULL,
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes INT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'CONFIRMED',
    cancellation_reason VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_appointments_reference_number UNIQUE (reference_number),
    CONSTRAINT fk_appointments_dealership FOREIGN KEY (dealership_id) REFERENCES dealerships (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_service_type FOREIGN KEY (service_type_id) REFERENCES service_types (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_service_bay FOREIGN KEY (service_bay_id) REFERENCES service_bays (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_technician FOREIGN KEY (technician_id) REFERENCES technicians (id) ON DELETE RESTRICT,
    CONSTRAINT chk_appointments_time_range CHECK (end_time > start_time),
    CONSTRAINT chk_appointments_duration CHECK (duration_minutes > 0),
    CONSTRAINT chk_appointments_status CHECK (status IN ('CONFIRMED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'RESCHEDULED'))
);

-- Optimized Composite Indexes for Temporal Range Overlap Queries & Concurrency
-- Notice: Foreign keys are BIGINT (8 bytes), keeping these composite indexes compact!
CREATE INDEX IF NOT EXISTS idx_appointments_bay_time ON appointments (service_bay_id, start_time, end_time);
CREATE INDEX IF NOT EXISTS idx_appointments_tech_time ON appointments (technician_id, start_time, end_time);
CREATE INDEX IF NOT EXISTS idx_appointments_dealer_time ON appointments (dealership_id, start_time, end_time);
CREATE INDEX IF NOT EXISTS idx_appointments_customer ON appointments (customer_id);
CREATE INDEX IF NOT EXISTS idx_appointments_vin ON appointments (vehicle_vin);
CREATE INDEX IF NOT EXISTS idx_appointments_status ON appointments (status);

-- ----------------------------------------------------------------------------
-- Table: appointment_audit_logs
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS appointment_audit_logs (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    appointment_id UUID NOT NULL,
    action VARCHAR(50) NOT NULL,
    status_from VARCHAR(30),
    status_to VARCHAR(30) NOT NULL,
    reason VARCHAR(255),
    performed_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_audit_appointment_id ON appointment_audit_logs (appointment_id);
CREATE INDEX IF NOT EXISTS idx_audit_created_at ON appointment_audit_logs (created_at);
