-- Script: V1__init_schema.sql
-- Compliance: docs/rules/database-design-and-script-rules.md
-- Engine: PostgreSQL 17
-- Architectural Strategy: Hybrid Key Architecture (Pragmatic System Design)
--   - Master/Reference Data: BIGINT IDENTITY PKs for compact 8-byte indexes and fast joins.
--   - Transactional Data: UUID PKs for secure, un-enumerable public API references.
